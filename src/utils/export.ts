export function generateSitemap(pages: Page[], appUrl: string): string {
  const url = appUrl || "https://siteforge.netlify.app";
  const dateStr = new Date().toISOString().split('T')[0];
  const urlEntries = pages.map(p => {
    const pPath = p.isHomepage ? "" : `/${p.name.toLowerCase().replace(/\s+/g, '-')}`;
    return `
  <url>
    <loc>${url}${pPath}</loc>
    <lastmod>${dateStr}</lastmod>
    <priority>${p.isHomepage ? "1.0" : "0.8"}</priority>
  </url>`.trim();
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urlEntries}
</urlset>`.trim();
}

export function generateRobots(appUrl: string): string {
  const url = appUrl || "https://siteforge.netlify.app";
  return `
# robots.txt generated by SiteForge
User-agent: *
Allow: /

Sitemap: ${url}/sitemap.xml
  `.trim();
}


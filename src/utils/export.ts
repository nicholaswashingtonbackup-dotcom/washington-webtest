/**
 * Builds standard optimized production HTML page containing custom layouts
 */
export function buildProductionHTML(
  pages: Page[],
  tokens: DesignTokens,
  activePageId: string,
  options: ExportOptions,
  projectHostUrl = ""
): string {
  const activePage = pages.find(p => p.id === activePageId) || pages[0];
  if (!activePage) return "<!-- No active contents -->";

  // Compile CSS custom properties based on design system
  const cssVariables = `
    :root {
      --primary-color: ${tokens.primaryColor};
      --secondary-color: ${tokens.secondaryColor};
      --accent-color: ${tokens.accentColor};
      --font-family: ${tokens.fontFamily || 'sans-serif'};
      --heading-font: ${tokens.headingFont || 'sans-serif'};
      --border-radius: ${tokens.borderRadius || '12px'};
      --spacing-scale: ${tokens.spacingScale || 4}px;
      --bg-color: ${tokens.backgroundColor || '#0f0f23'};
      --text-color: ${tokens.textColor || '#e2e8f0'};
      --gradient-start: ${tokens.gradientStart || tokens.primaryColor};
      --gradient-end: ${tokens.gradientEnd || tokens.secondaryColor};
    }
  `;

  // HTML Head items
  const metaTitle = activePage.metaTitle || `${activePage.name} - Designed with SiteForge`;
  const metaDesc = activePage.metaDescription || "Production-ready website generated using SiteForge.";
  
  let html = `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${metaTitle}</title>
  <meta name="description" content="${metaDesc}">
  
  <!-- Fonts -->
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Space+Grotesk:wght@500;700&family=Outfit:wght@400;500;600;700&family=Playfair+Display:ital,wght@0,600;0,700;1,400&family=Plus+Jakarta+Sans:wght@500;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
  
  <!-- Tailwind CSS -->
  <script src="https://cdn.tailwindcss.com"></script>
  <script>
    tailwind.config = {
      theme: {
        extend: {
          borderRadius: {
            'custom': '${tokens.borderRadius || '12px'}'
          }
        }
      }
    }
  </script>

  <!-- Favicon -->
  <link rel="icon" type="image/svg+xml" href="data:image/svg+xml;utf8,${encodeURIComponent(generateFaviconSVG(tokens.primaryColor))}">
  
  <style>
    ${cssVariables}
    
    body {
      font-family: var(--font-family);
      background-color: var(--bg-color);
      color: var(--text-color);
      margin: 0;
      padding: 0;
    }
    
    h1, h2, h3, h4, h5, h6 {
      font-family: var(--heading-font);
    }
    
    /* Custom Scrollbar */
    ::-webkit-scrollbar {
      width: 8px;
    }
    ::-webkit-scrollbar-track {
      background: var(--bg-color);
    }
    ::-webkit-scrollbar-thumb {
      background: var(--primary-color);
      border-radius: 4px;
    }
    
    ${activePage.css || ''}
  </style>
</head>
<body>
  
  <!-- MAIN MOUNT CANVAS -->
  <div id="siteforge-root">
    ${activePage.html}
  </div>

  <script>
    // Universal accordions expand functionality
    document.addEventListener("DOMContentLoaded", () => {
      const accs = document.querySelectorAll("#siteforge-root h4.cursor-pointer");
      accs.forEach(acc => {
        acc.addEventListener("click", () => {
          const content = acc.nextElementSibling;
          if (content) {
            content.classList.toggle("hidden");
            const indicator = acc.querySelector("span");
            if (indicator) {
              indicator.textContent = content.classList.contains("hidden") ? "+" : "-";
            }
          }
        });
      });
    });
  </script>
</body>
</html>
  `.trim();

  // Perform minification if options state so
  if (options.minifyHTML) {
    // Remove extra linebreaks and spaces
    html = html.replace(/\s+/g, ' ');
  }

  return html;
}

/**
 * High-quality React code parsing of active elements
 */
export function buildReactComponentCode(name: string, htmlStr: string, tokens: DesignTokens): string {
  // Simple sanitizer to convert standard HTML properties (class -> className, style as string to style as object)
  let componentName = name.replace(/[^a-zA-Z0-9]/g, '');
  componentName = componentName.charAt(0).toUpperCase() + componentName.slice(1);
  
  let reactHTML = htmlStr;
  reactHTML = reactHTML.replace(/\bclass=/g, 'className=');
  reactHTML = reactHTML.replace(/\bfor=/g, 'htmlFor=');
  reactHTML = reactHTML.replace(/\bautocomplete=/g, 'autoComplete=');
  
  // Strip comments
  reactHTML = reactHTML.replace(/<!--[\s\S]*?-->/g, '');

  return `
/**
 * Generated by SiteForge Studio
 * Adaptable component with pure customized design tokens
 */

import React from 'react';

export default function ${componentName}Component() {
  const inlineTheme = {
    "--primary-color": "${tokens.primaryColor}",
    "--secondary-color": "${tokens.secondaryColor}",
    "--accent-color": "${tokens.accentColor}",
    "--font-family": "${tokens.fontFamily}",
    "--heading-font": "${tokens.headingFont}",
    "--border-radius": "${tokens.borderRadius}",
    "--bg-color": "${tokens.backgroundColor}",
    "--text-color": "${tokens.textColor}",
  } as React.CSSProperties;

  return (
    <div style={inlineTheme} className="min-h-screen">
      ${reactHTML}
    </div>
  );
}
  `.trim();
}

